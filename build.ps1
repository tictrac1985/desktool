# DeskMate build script — compiles with VS BuildTools Roslyn csc against .NET Framework 4.8 GAC assemblies.
param(
    [switch]$SkipTests,
    [switch]$SkipInstaller,
    [switch]$UiSmoke,
    # Authenticode signing. Pass -SignThumbprint with a cert installed in Cert:\CurrentUser\My,
    # or -SignPfx + -SignPfxPassword. Unsigned builds still work; they just trip SmartScreen.
    [string]$SignThumbprint,
    [string]$SignPfx,
    [string]$SignPfxPassword,
    [string]$TimestampUrl = "http://timestamp.digicert.com"
)
$ErrorActionPreference = "Stop"
$root = $PSScriptRoot

# Roslyn csc lives in different spots per VS edition — probe the usual suspects, then
# fall back to vswhere so the build survives a BuildTools→Community/Pro/Enterprise switch.
$cscCandidates = @(
    "C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\MSBuild\Current\Bin\Roslyn\csc.exe",
    "C:\Program Files\Microsoft Visual Studio\2022\BuildTools\MSBuild\Current\Bin\Roslyn\csc.exe",
    "C:\Program Files\Microsoft Visual Studio\2022\Enterprise\MSBuild\Current\Bin\Roslyn\csc.exe",
    "C:\Program Files\Microsoft Visual Studio\2022\Professional\MSBuild\Current\Bin\Roslyn\csc.exe",
    "C:\Program Files (x86)\Microsoft Visual Studio\2022\Community\MSBuild\Current\Bin\Roslyn\csc.exe",
    "C:\Program Files\Microsoft Visual Studio\2022\Community\MSBuild\Current\Bin\Roslyn\csc.exe"
)
$csc = $cscCandidates | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $csc) {
    $vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
    if (Test-Path $vswhere) {
        # -products * : without it vswhere skips Build Tools installs (it only lists the IDEs),
        # which is exactly the edition this script recommends; also covers VS 2026 and later.
        $csc = & $vswhere -latest -products * -requires Microsoft.Component.MSBuild `
                   -find "MSBuild\**\Bin\Roslyn\csc.exe" | Select-Object -First 1
    }
}
$fw   = "C:\Windows\Microsoft.NET\Framework64\v4.0.30319"
if (-not $csc -or -not (Test-Path $csc)) { throw "csc (Roslyn) not found - install Visual Studio Build Tools (2022 or newer) with the '.NET desktop build tools' workload" }
Write-Host "csc: $csc"

$dist = Join-Path $root "dist"
$obj  = Join-Path $root "obj"
New-Item -ItemType Directory -Force $dist | Out-Null
New-Item -ItemType Directory -Force $obj  | Out-Null
New-Item -ItemType Directory -Force (Join-Path $root "assets") | Out-Null

# Clean-slate rule: stale intermediates from previous runs (old test exes, abandoned
# outputs) must never leak into a new delivery. Wipe obj except uishots — the smoke
# run rewrites that folder itself when -UiSmoke is on.
Get-ChildItem $obj -Force -ErrorAction SilentlyContinue |
    Where-Object { $_.Name -ne "uishots" } |
    Remove-Item -Recurse -Force -ErrorAction SilentlyContinue

# ---------------- Build stamp ----------------
# The fourth version part is the number of commits on the checked-out branch. The same
# commit therefore gets the same version on any machine and in the GitHub workflow, and a
# later commit always gets a higher one — which is the ordering the in-app updater relies on
# (src\Logic\UpdateCore.cs). No git, or not a clone (a source zip): the part is 0.
function Get-BuildRevision {
    if ($env:DESKMATE_BUILD -match '^\d+$') { return $env:DESKMATE_BUILD }
    $prev = $ErrorActionPreference
    $ErrorActionPreference = "Continue"     # git chatter on stderr must not abort the build
    try {
        if ((Get-Command git -ErrorAction SilentlyContinue) -and (Test-Path (Join-Path $root ".git"))) {
            $n = (& git -C $root rev-list --count HEAD 2>$null | Select-Object -First 1)
            if ($LASTEXITCODE -eq 0 -and "$n" -match '^\d+$' -and [int]$n -le 65000) { return "$n".Trim() }
        }
    } catch { }
    finally { $ErrorActionPreference = $prev }
    return "0"
}
$rev = Get-BuildRevision
$stamp = Join-Path $obj "BuildStamp.cs"
@"
// Generated by build.ps1 - do not edit, do not commit.
namespace DeskMate.Core
{
    public static class BuildStamp
    {
        public const string Revision = "$rev";
    }
}
"@ | Set-Content -Path $stamp -Encoding UTF8
$verText = (Select-String -Path (Join-Path $root "src\Core\AppVersion.cs") -Pattern 'Text = "([\d.]+)"').Matches[0].Groups[1].Value
Write-Host "version: $verText.$rev"

# ---------------- Icon generation ----------------
function New-AppIcon([string]$icoPath) {
    Add-Type -AssemblyName System.Drawing
    $sizes = 16, 24, 32, 48, 64, 256
    $pngs = @()
    foreach ($s in $sizes) {
        $bmp = New-Object System.Drawing.Bitmap($s, $s)
        $g = [System.Drawing.Graphics]::FromImage($bmp)
        $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
        # rounded dark square
        $r = [float]($s * 0.22); $w = [float]($s - 1)
        $path = New-Object System.Drawing.Drawing2D.GraphicsPath
        $path.AddArc(0, 0, 2*$r, 2*$r, 180, 90)
        $path.AddArc($w - 2*$r, 0, 2*$r, 2*$r, 270, 90)
        $path.AddArc($w - 2*$r, $w - 2*$r, 2*$r, 2*$r, 0, 90)
        $path.AddArc(0, $w - 2*$r, 2*$r, 2*$r, 90, 90)
        $path.CloseFigure()
        $bg = New-Object System.Drawing.Drawing2D.LinearGradientBrush(
            (New-Object System.Drawing.Point(0,0)), (New-Object System.Drawing.Point(0,$s)),
            [System.Drawing.Color]::FromArgb(255, 34, 41, 58), [System.Drawing.Color]::FromArgb(255, 15, 19, 28))
        $g.FillPath($bg, $path)
        # dial
        $cx = [float]($s / 2.0); $cy = [float]($s / 2.0); $rad = [float]($s * 0.33)
        $penDial = New-Object System.Drawing.Pen([System.Drawing.Color]::FromArgb(215, 255, 255, 255), [Math]::Max(1.0, $s * 0.05))
        $g.DrawEllipse($penDial, $cx - $rad, $cy - $rad, 2*$rad, 2*$rad)
        # hands at 10:10
        $penH = New-Object System.Drawing.Pen([System.Drawing.Color]::FromArgb(255, 255, 198, 110), [Math]::Max(1.0, $s * 0.07))
        $penH.StartCap = "Round"; $penH.EndCap = "Round"
        $penM = New-Object System.Drawing.Pen([System.Drawing.Color]::White, [Math]::Max(1.0, $s * 0.055))
        $penM.StartCap = "Round"; $penM.EndCap = "Round"
        $aH = -150 * [Math]::PI / 180.0   # hour hand toward 10
        $aM = -30 * [Math]::PI / 180.0    # minute hand toward 2
        $g.DrawLine($penH, $cx, $cy, [float]($cx + [Math]::Sin($aH) * $rad * 0.55), [float]($cy - [Math]::Cos($aH) * $rad * 0.55))
        $g.DrawLine($penM, $cx, $cy, [float]($cx + [Math]::Sin($aM) * $rad * 0.8),  [float]($cy - [Math]::Cos($aM) * $rad * 0.8))
        $dotR = [Math]::Max(1.0, $s * 0.045)
        $g.FillEllipse((New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(255, 255, 198, 110))), $cx - $dotR, $cy - $dotR, 2*$dotR, 2*$dotR)
        $g.Dispose()
        $ms = New-Object System.IO.MemoryStream
        $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png)
        $bmp.Dispose()
        $pngs += ,@($s, $ms.ToArray())
    }
    # pack PNG-ICO
    $fs = [System.IO.File]::Create($icoPath)
    $bw = New-Object System.IO.BinaryWriter($fs)
    $bw.Write([uint16]0); $bw.Write([uint16]1); $bw.Write([uint16]$pngs.Count)
    $offset = 6 + 16 * $pngs.Count
    foreach ($p in $pngs) {
        $s = $p[0]; $data = $p[1]
        $b = 0; if ($s -lt 256) { $b = $s }
        $bw.Write([byte]$b); $bw.Write([byte]$b); $bw.Write([byte]0); $bw.Write([byte]0)
        $bw.Write([uint16]1); $bw.Write([uint16]32)
        $bw.Write([uint32]$data.Length); $bw.Write([uint32]$offset)
        $offset += $data.Length
    }
    foreach ($p in $pngs) { $bw.Write([byte[]]$p[1]) }
    $bw.Close(); $fs.Close()
}

$ico = Join-Path $root "assets\app.ico"
if (-not (Test-Path $ico)) {
    Write-Host "Generating app.ico ..."
    New-AppIcon $ico
}

# ---------------- References ----------------
$xaml = Join-Path $fw "System.Xaml.dll"
if (-not (Test-Path $xaml)) { $xaml = Join-Path $fw "WPF\System.Xaml.dll" }
$refsApp = @(
    "$fw\mscorlib.dll", "$fw\System.dll", "$fw\System.Core.dll", "$fw\System.Xml.dll",
    "$fw\System.Drawing.dll", "$fw\System.Windows.Forms.dll", "$fw\Microsoft.CSharp.dll",
    "$fw\System.Security.dll",
    $xaml, "$fw\WPF\WindowsBase.dll", "$fw\WPF\PresentationCore.dll", "$fw\WPF\PresentationFramework.dll"
)
# System.Security carries ProtectedData (DPAPI), used by Core\Secret.cs
$refsPure = @("$fw\mscorlib.dll", "$fw\System.dll", "$fw\System.Core.dll", "$fw\System.Xml.dll",
              "$fw\System.Security.dll", "$fw\System.Drawing.dll")

# ---------------- Authenticode signing ----------------
function Get-SignTool {
    $roots = @("${env:ProgramFiles(x86)}\Windows Kits\10\bin", "$env:ProgramFiles\Windows Kits\10\bin")
    foreach ($r in $roots) {
        if (-not (Test-Path $r)) { continue }
        $found = Get-ChildItem $r -Recurse -Filter signtool.exe -ErrorAction SilentlyContinue |
                 Where-Object { $_.FullName -match '\\x64\\' } |
                 Sort-Object FullName -Descending | Select-Object -First 1
        if ($found) { return $found.FullName }
    }
    return $null
}

function Invoke-Sign([string]$path) {
    if (-not $SignThumbprint -and -not $SignPfx) { return }   # unsigned build: nothing to do
    $signtool = Get-SignTool
    if (-not $signtool) { throw "signtool.exe not found - install the Windows 10/11 SDK 'Signing Tools' feature" }
    $a = @("sign", "/fd", "SHA256", "/td", "SHA256", "/tr", $TimestampUrl)
    if ($SignThumbprint) { $a += @("/sha1", $SignThumbprint) }
    else {
        $a += @("/f", $SignPfx)
        if ($SignPfxPassword) { $a += @("/p", $SignPfxPassword) }
    }
    $a += $path
    & $signtool @a
    if ($LASTEXITCODE -ne 0) { throw "signing failed for $path" }
    Write-Host "Signed -> $path" -ForegroundColor Green
}

function Invoke-Csc([string]$out, [string]$target, [string[]]$sources, [string[]]$refs, [string[]]$extra) {
    $args = @("/nologo", "/codepage:65001", "/langversion:latest", "/optimize+", "/platform:anycpu",
              "/target:$target", "/out:$out", "/noconfig", "/nostdlib+")
    foreach ($r in $refs) { $args += "/reference:$r" }
    if ($extra) { $args += $extra }
    $args += $sources
    & $csc @args
    if ($LASTEXITCODE -ne 0) { throw "csc failed for $out" }
}

# ---------------- Self tests ----------------
$pureSources = @($stamp) + @(Get-ChildItem (Join-Path $root "src\Core") -Filter *.cs | ForEach-Object { $_.FullName })
$logicDir = Join-Path $root "src\Logic"
if (Test-Path $logicDir) { $pureSources += @(Get-ChildItem $logicDir -Filter *.cs | ForEach-Object { $_.FullName }) }
$selfTest = Join-Path $root "tests\SelfTest.cs"
if ((-not $SkipTests) -and (Test-Path $selfTest)) {
    Write-Host "Building SelfTest ..."
    $stExe = Join-Path $obj "SelfTest.exe"
    Invoke-Csc $stExe "exe" (@($selfTest) + $pureSources) $refsPure $null
    Write-Host "Running SelfTest ..."
    & $stExe
    if ($LASTEXITCODE -ne 0) { throw "Self tests FAILED" }
    Write-Host "Self tests passed." -ForegroundColor Green
}

# ---------------- Main app ----------------
Write-Host "Building DeskMate.exe ..."
$appSources = @($stamp) + @(Get-ChildItem (Join-Path $root "src") -Recurse -Filter *.cs | ForEach-Object { $_.FullName })
$appExe   = Join-Path $dist "DeskMate.exe"

# The widget is usually RUNNING from dist\ while it is being rebuilt, and Windows will not
# let a running image be overwritten — the build used to die here with a cryptic csc error.
# A running exe can be renamed, though: move it aside and build into the freed name. The
# running copy keeps working until it is restarted; the stray file is swept on the next build.
function Clear-OutputFile([string]$path) {
    if (-not (Test-Path $path)) { return }
    # not locked: leave it alone, csc replaces it only when the compile succeeds
    try { $fs = [System.IO.File]::Open($path, 'Open', 'ReadWrite', 'None'); $fs.Close(); return } catch { }
    $aside = "$path." + [DateTime]::UtcNow.Ticks.ToString("x") + ".old"
    try {
        Move-Item $path $aside -Force -ErrorAction Stop
        Write-Host "note: $(Split-Path $path -Leaf) is running - built beside it; restart the app to use the new build" -ForegroundColor Yellow
    } catch { throw "cannot replace $path - close DeskMate and build again" }
}
Get-ChildItem $dist -Filter *.old -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue
Get-ChildItem $dist -Filter *.new -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue
Clear-OutputFile $appExe
$manifest = Join-Path $root "src\app.manifest"
# v1.11: the interface font (Tajawal, SIL OFL — assets\fonts\OFL.txt) travels inside the exe;
# UI\AppFonts.cs unpacks it to %LocalAppData%\DeskMate\fonts on first run
$fontRes = @(Get-ChildItem (Join-Path $root "assets\fonts") -Filter *.ttf -ErrorAction SilentlyContinue |
    ForEach-Object { "/resource:$($_.FullName),DeskMate.Fonts.$($_.Name)" })
$appExtra = @("/win32icon:$ico") + $fontRes
if (Test-Path $manifest) { $appExtra += "/win32manifest:$manifest" }
Invoke-Csc $appExe "winexe" $appSources $refsApp $appExtra
# sign before embedding: the installer carries this exact file as its payload
Invoke-Sign $appExe
Write-Host "OK -> $appExe" -ForegroundColor Green

# ---------------- Installer ----------------
$setupSrc = Join-Path $root "installer\Setup.cs"
if ((-not $SkipInstaller) -and (Test-Path $setupSrc)) {
    Write-Host "Building DeskMateSetup.exe ..."
    $setupExe = Join-Path $dist "DeskMateSetup.exe"
    $refsSetup = @("$fw\mscorlib.dll", "$fw\System.dll", "$fw\System.Core.dll",
                   "$fw\System.Drawing.dll", "$fw\System.Windows.Forms.dll")
    $setupExtra = @("/win32icon:$ico", "/resource:$appExe,DeskMate.Payload")
    if (Test-Path $manifest) { $setupExtra += "/win32manifest:$manifest" }
    # AppVersion.cs is compiled in too: one version source for app and installer alike.
    # SetupAssemblyInfo.cs turns that constant into real file metadata — without it the
    # installer shipped as 0.0.0.0 in Explorer's Details tab.
    Clear-OutputFile $setupExe
    Invoke-Csc $setupExe "winexe" @($setupSrc, $stamp,
        (Join-Path $root "src\Core\AppVersion.cs"),
        (Join-Path $root "installer\SetupAssemblyInfo.cs")) $refsSetup $setupExtra
    Invoke-Sign $setupExe
    Write-Host "OK -> $setupExe" -ForegroundColor Green
}
# ---------------- UI smoke screenshots (optional) ----------------
$uiSmokeSrc = Join-Path $root "tests\UiSmoke.cs"
if ($UiSmoke -and (Test-Path $uiSmokeSrc)) {
    Write-Host "Building UiSmoke ..."
    $smokeExe = Join-Path $obj "UiSmoke.exe"
    Invoke-Csc $smokeExe "winexe" ($appSources + @($uiSmokeSrc)) $refsApp (@("/main:UiSmoke", "/win32icon:$ico") + $fontRes)
    $shots = Join-Path $obj "uishots"
    Write-Host "Capturing UI screenshots -> $shots"
    & $smokeExe $shots | Out-Host
    # the smoke run now reports every swallowed failure through its exit code
    if ($LASTEXITCODE -ne 0) { throw "UiSmoke FAILED ($LASTEXITCODE) - see FAIL lines above" }
}

# ---------------- Delivery folder ----------------
# The user-facing contract: a full build ships exactly two files in finish\ — the
# portable app and the installer, both version-named. Anything older or unrelated
# from previous deliveries is removed first.
if (-not $SkipInstaller) {
    $ver = $verText
    $finish = Join-Path $root "finish"
    New-Item -ItemType Directory -Force $finish | Out-Null
    Get-ChildItem $finish -Force -ErrorAction SilentlyContinue | Remove-Item -Recurse -Force -ErrorAction SilentlyContinue
    Copy-Item $appExe (Join-Path $finish "DeskMate-Portable-$ver.exe")
    $setupExe = Join-Path $dist "DeskMateSetup.exe"
    if (Test-Path $setupExe) { Copy-Item $setupExe (Join-Path $finish "DeskMate-Setup-$ver.exe") }
    Write-Host "Delivered -> finish\DeskMate-Portable-$ver.exe + finish\DeskMate-Setup-$ver.exe" -ForegroundColor Green
}

Write-Host "Build complete." -ForegroundColor Green
